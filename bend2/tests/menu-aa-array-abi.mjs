import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import * as Bend from '../../.artifacts/toolchains/bend/bend2/bend.ts';
import * as Comp from '../../.artifacts/toolchains/bend/bend2/comp.ts';
import { resolveBaseForeignImports } from '../tools/loader-v2.ts';
process.env.BEND_NO_TELEMETRY = '1';
const root = path.resolve(import.meta.dirname, '../..');
const book = Bend.book_nil();
await Bend.book_load(book, path.join(root, 'bend2/tests/menu-aa-array-abi.bend').replaceAll('\\', '/'), '', new Map());
resolveBaseForeignImports(book);
Bend.book_valid(book);
assert.equal(book.hols + book.open, 0);
const file = path.join(root, '.artifacts/bend2/v2-preview/menu-aa-array-abi.mjs');
fs.mkdirSync(path.dirname(file), { recursive: true });
fs.writeFileSync(file, Comp.js_lib(book, ['read_second'], ['read_second']));
const api = (await import(pathToFileURL(file).href)).default;
assert.equal(api.read_second([7,42,99,0]), 42);
assert.equal(api.read_second(Uint8Array.from([7,42,99,0])), 42);
console.log('Bend Array<U32> JS ABI accepted power-of-two Array and Uint8Array');
